/**
 * 教材章号范围表（只服务「按学期 · 单元章节」这一种看法）。
 *
 * ## 为什么需要这份表
 *
 * 数学、物理、化学的章（单元）号是**跨册连续编号**的：
 * 数学七上 1—6 章、七下 7—12 章、八上 13—18 章……一路到九下第 34 章。
 * 于是只看某一册的数据**推不出「这一册应该有哪几章」**——某章整章还没录内容时，
 * 它在数据里根本不存在，按数据分组就会把这一章整个跳过，学生以为教材没有它
 * （作者也看不到待补清单）。
 *
 * 这份表补的正是「这一册从第几章到第几章」，表里的数字与本站数据的编号口径一致
 * （人教版 2024 版：数学 1—34 章、物理 1—22 章、化学第一—十二单元）。
 * 表里**只写章号范围、不写章名**：缺内容的章以「第 N 章（本站暂无内容）」占位，
 * 不替教材编标题——标题一旦写错，比空着更误导。
 *
 * 没在这张表里的学科（历史、道法等）走**兜底规则**：以本册数据的最大章号为上界、
 * 从 1 开始补内部缺口。它们的单元号每册各自从 1 起算，兜底不会跨册串号。
 */
import type { GradeId } from '../types';

export interface TextbookSerial {
  /** 这一科用的是「章」还是「单元」 */
  kind: '章' | '单元';
  /** 每册的章号范围 [起, 止] */
  terms: Partial<Record<GradeId, [number, number]>>;
}


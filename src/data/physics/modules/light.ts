/** 一个谐波分量：振幅（画布单位）与在整段里出现的完整波数 */
interface WaveHarmonic {
  amp: number;
  waves: number;
}

/**
 * 取样正弦（或若干谐波叠加）波形，得到 `curve` 图元需要的点列。
 *
 * 为什么要用它：波形图的判读全靠「波疏还是密」「波高还是矮」「形状是不是正弦」，
 * 手写坐标一旦不平滑或周期写错，图讲的就是错的物理。这里按数学式取样，
 * 保证「波数多 = 频率高」「振幅大 = 响度大」在图上一定成立。
 */
function wavePoints(
  x0: number,
  x1: number,
  axisY: number,
  harmonics: WaveHarmonic[],
  steps = 96,
): [number, number][] {
  const out: [number, number][] = [];
  for (let i = 0; i <= steps; i += 1) {
    const t = i / steps;
    let dy = 0;
    for (const h of harmonics) dy += h.amp * Math.sin(2 * Math.PI * h.waves * t);
    out.push([
      Math.round((x0 + (x1 - x0) * t) * 100) / 100,
      Math.round((axisY - dy) * 100) / 100,
    ]);
  }
  return out;
}

/**
 * 疏密波示意：把介质画成一串竖线，竖线挤在一起的地方是密部、拉开的地方是疏部。
 *
 * 位置映射 x(t) = x0 + (x1−x0)(t + 0.045 sin(2π·waves·t))，导数恒大于 0，竖线不会交错。
 */
function compressionLines(
  x0: number,
  x1: number,
  yTop: number,
  yBottom: number,
  waves = 2,
  count = 46,
): FigurePrim[] {
  const out: FigurePrim[] = [];
  for (let i = 0; i <= count; i += 1) {
    const t = i / count;
    const x = Math.round((x0 + (x1 - x0) * (t + 0.045 * Math.sin(2 * Math.PI * waves * t))) * 100) / 100;
    out.push({ t: 'line', x1: x, y1: yTop, x2: x, y2: yBottom, tone: 'muted', width: 0.5 });
  }
  return out;
}

/**
 * 圆弧取样：把「圆心、半径、起止角」换算成 `curve` 图元需要的点列。
 *
 * 为什么不直接用 `arc` 图元：`arc` 的 large-arc 标志是拿「度数」去和 `Math.PI` 比的
 * （`Math.abs(a2 - a1) > Math.PI`），于是任意跨度超过约 3° 的弧都会被当成「大于半圆」，
 * 画出来是反向的大弧。球面镜、水波这类弧线必须凹凸方向正确，所以这里改用取样点列，
 * 方向与弧长完全由参数决定（角度按数学直觉写，逆时针为正）。
 */
function arcPoints(
  cx: number,
  cy: number,
  r: number,
  fromDeg: number,
  toDeg: number,
  steps = 48,
): [number, number][] {
  const out: [number, number][] = [];
  for (let i = 0; i <= steps; i += 1) {
    const deg = fromDeg + ((toDeg - fromDeg) * i) / steps;
    out.push([
      Math.round((cx + r * Math.cos((deg * Math.PI) / 180)) * 100) / 100,
      Math.round((cy - r * Math.sin((deg * Math.PI) / 180)) * 100) / 100,
    ]);
  }
  return out;
}

